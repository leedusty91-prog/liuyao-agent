def liuqin_of(palace_wx: str, yao_wx: str) -> str:
    """以卦宫五行为我，定爻之六亲。"""
    if yao_wx == palace_wx:
        return "兄弟"
    if SHENG[yao_wx] == palace_wx:
        return "父母"
    if SHENG[palace_wx] == yao_wx:
        return "子孙"
    if KE[yao_wx] == palace_wx:
        return "官鬼"
    return "妻财"


def wuxing_relation(a: str, b: str) -> str:
    """a 对 b 的作用：同 / 生(a生b) / 克(a克b) / 被生(b生a) / 被克(b克a)。"""
    if a == b:
        return "同"
    if SHENG[a] == b:
        return "生"
    if KE[a] == b:
        return "克"
    if SHENG[b] == a:
        return "被生"
    return "被克"
